from __future__ import annotations

import json
from pathlib import Path
from typing import Any


PROJECT_ROOT = Path(__file__).resolve().parent.parent
REGISTRY_DIR = PROJECT_ROOT / "registry"
LOG_FILE = PROJECT_ROOT / "research_log.md"


def load_experiments() -> list[dict[str, Any]]:
    experiments = []

    if not REGISTRY_DIR.exists():
        return experiments

    for file_path in REGISTRY_DIR.rglob("*.json"):
        with file_path.open("r", encoding="utf-8") as file:
            experiments.append(json.load(file))

    experiments.sort(
        key=lambda item: item.get("created_at", ""),
        reverse=True,
    )

    return experiments


def generate_log(experiments: list[dict[str, Any]]) -> str:
    lines = [
        "# Research Log",
        "",
        "> This file is automatically generated from the experiment registry.",
        "> Do not edit manually.",
        "",
        "---",
        "",
    ]

    if not experiments:
        lines.append(
            "No successful experiments have been registered yet."
        )
        return "\n".join(lines) + "\n"

    for experiment in experiments:
        experiment_id = experiment["experiment_id"]
        created_at = experiment["created_at"]
        topic = experiment["topic"]
        model = experiment["model"]
        objective = experiment["objective"]
        dataset = experiment["dataset"]
        owner = experiment["owner"]
        status = experiment["status"]

        lines.extend(
            [
                f"## {created_at}",
                "",
                f"### {experiment_id}",
                "",
                f"**Topic:** {topic}  ",
                f"**Model:** {model}  ",
                f"**Dataset:** {dataset}  ",
                f"**Owner:** {owner}  ",
                f"**Status:** {status}",
                "",
                "**Objective**",
                "",
                objective,
                "",
                "**Metrics**",
                "",
            ]
        )

        for metric_name, metric_value in experiment["metrics"].items():
            if isinstance(metric_value, (int, float)):
                formatted_value = f"{metric_value:.4f}"
            else:
                formatted_value = str(metric_value)

            lines.append(
                f"- {metric_name}: {formatted_value}"
            )

        lines.extend(
            [
                "",
                "**Resources**",
                "",
            ]
        )

        notebook = experiment.get("notebook")
        kaggle = experiment.get("kaggle") or {}
        kaggle_url = kaggle.get("url")

        if notebook:
            lines.append(
                f"- Notebook: {notebook}"
            )

        if kaggle_url:
            lines.append(
                f"- Kaggle: {kaggle_url}"
            )

        if not notebook and not kaggle_url:
            lines.append(
                "- Notebook: Not linked yet"
            )
            lines.append(
                "- Kaggle: Not linked yet"
            )

        lines.extend(
            [
                "",
                "---",
                "",
            ]
        )

    return "\n".join(lines)


def main() -> int:
    experiments = load_experiments()
    content = generate_log(experiments)

    LOG_FILE.write_text(
        content,
        encoding="utf-8",
    )

    print(f"Research log generated: {LOG_FILE}")
    print(f"Experiments found: {len(experiments)}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
