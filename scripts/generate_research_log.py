from __future__ import annotations

import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True


ROOT_DIR = Path(__file__).resolve().parent.parent
REGISTRY_DIR = ROOT_DIR / "registry"
LOG_FILE = ROOT_DIR / "research_log.md"


def load_experiments() -> list[dict]:

    experiments = []

    for file_path in sorted(REGISTRY_DIR.rglob("*.json")):

        with file_path.open("r", encoding="utf-8") as file:
            record = json.load(file)

        experiments.append(record)

    experiments.sort(
        key=lambda item: (
            item.get("created_at", ""),
            item.get("experiment_id", ""),
        ),
        reverse=True,
    )

    return experiments


def format_metric(value) -> str:

    if isinstance(value, float):
        return f"{value:.4f}"

    return str(value)


def main() -> None:

    experiments = load_experiments()

    # Deterministik: pakai waktu eksperimen terbaru, bukan jam saat workflow
    # berjalan (timestamp jam-sekarang adalah sumber konflik antar-branch).
    last_updated = (
        experiments[0].get("created_at", "-") if experiments else "-"
    )

    lines = [
        "# Research Log",
        "",
        "Chronological record of registered modelling experiments.",
        "",
        "> **This file is automatically generated. "
        "Do not edit manually.**",
        "",
        f"Last registry update: `{last_updated}`",
        "",
        "---",
        "",
    ]

    if not experiments:

        lines.extend(
            [
                "No experiments have been registered yet.",
                "",
            ]
        )

    for experiment in experiments:

        experiment_id = experiment.get(
            "experiment_id",
            "-",
        )

        lines.extend(
            [
                f"## {experiment_id}",
                "",
                f"**Date:** {experiment.get('created_at', '-')}",
                "",
                f"**Topic:** {experiment.get('topic', '-')}",
                "",
                f"**Model:** {experiment.get('model', '-')}",
                "",
                f"**Owner:** {experiment.get('owner', '-')}",
                "",
                f"**Dataset:** {experiment.get('dataset', '-')}",
                "",
                f"**Status:** {experiment.get('status', '-')}",
                "",
                "### Objective",
                "",
                experiment.get(
                    "objective",
                    "-",
                ),
                "",
                "### Metrics",
                "",
            ]
        )

        metrics = experiment.get("metrics", {})

        if metrics:

            for metric_name, metric_value in metrics.items():

                lines.append(
                    f"- **{metric_name}:** "
                    f"{format_metric(metric_value)}"
                )

        else:
            lines.append("- No metrics recorded.")

        lines.extend(
            [
                "",
                "---",
                "",
            ]
        )

    LOG_FILE.write_text(
        "\n".join(lines),
        encoding="utf-8",
    )

    print(
        f"Research log generated successfully: {LOG_FILE}"
    )


if __name__ == "__main__":
    main()
